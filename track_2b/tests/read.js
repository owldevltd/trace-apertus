import fs from 'node:fs/promises';
import path from 'node:path';
import { levenshtein } from '../src/read/fluffy.js';

// The read text against the text layer of the PDF. Per read element: the words of the reference whose ink centre
// lies in the element, in reading order, against what the model returned. Verdicts: identical, near (distance at
// most NEAR of the length), different, empty. Character errors = distance per reference character. The Fluffy
// flag (approve) is held against the verdict: what it catches, and what it flags although the reading was right.
//
//   node tests/read.js --got=<read dir> [--out=<file.md>] <reference dir> [<reference dir> …]

const NEAR = 0.1;

// Distances are measured on the first characters only; a long paragraph that drifts once should not drown the rest.
const CUT = 250;

const LENGTHS = [ [ 0, 30, 'up to 30' ], [ 31, 120, '31 to 120' ], [ 121, Infinity, 'over 120' ] ];

// Thresholds for the Fluffy flag the table is laid out for; the one in the code is the decision, this is the data for it.
const THRESHOLDS = [ 0.005, 0.01, 0.02, 0.05, 0.1 ];

const refDirs = process.argv.slice( 2 ).filter( ( a ) => !a.startsWith( '--' ) );
const gotDir = ( process.argv.find( ( a ) => a.startsWith( '--got=' ) ) || '' ).slice( 6 );
const outFile = ( process.argv.find( ( a ) => a.startsWith( '--out=' ) ) || '' ).slice( 6 );
if ( !refDirs.length || !gotDir ) {
    console.log( 'usage: node tests/read.js --got=<read dir> [--out=<file.md>] <reference dir> [<reference dir> …]' );
    process.exit( 1 );
}

const files = [];
for ( const dir of refDirs ) {
    if ( !( await fs.stat( dir ) ).isDirectory() ) {
        continue;
    }
    for ( const f of ( await fs.readdir( dir ) ).filter( ( f ) => f.endsWith( '.json' ) ).sort() ) {
        files.push( path.join( dir, f ) );
    }
}

const rows = [];
const pages = [];
for ( const file of files ) {
    const name = path.basename( file, '.json' );
    let got;
    try {
        got = JSON.parse( await fs.readFile( path.join( gotDir, name + '-elements.json' ), 'utf8' ) );
    } catch {
        continue;
    }
    const ref = JSON.parse( await fs.readFile( file, 'utf8' ) );
    const words = ref.words.filter( ( w ) => w.ink );
    const read = got.filter( ( e ) => e.isOCR );
    const page = { name, read: read.length, outside: 0, noReference: 0 };
    for ( const w of words ) {
        const cx = w.ink.x + Math.floor( w.ink.w / 2 );
        const cy = w.ink.y + Math.floor( w.ink.h / 2 );
        if ( !read.some( ( e ) => cx >= e.x && cx <= e.x + e.width && cy >= e.y && cy <= e.y + e.height ) ) {
            page.outside++;
        }
    }
    got.forEach( ( e, i ) => {
        if ( !e.isOCR ) {
            return;
        }
        const want = plain( referenceText( words, e ) );
        const have = plain( e.content || '' );
        if ( want === '' ) {
            if ( have !== '' ) {
                page.noReference++;
            }
            return;
        }
        const dist = levenshtein( want.slice( 0, CUT ), have.slice( 0, CUT ) );
        const verdict = have === '' ? 'empty' : ( have === want ? 'identical' : ( dist <= NEAR * Math.max( 1, want.length ) ? 'near' : 'different' ) );
        rows.push( { page: name, i, len: want.length, verdict, dist, approve: !!e.approve, deviation: e.deviation ?? null, want, have } );
    } );
    page.rows = rows.filter( ( r ) => r.page === name );
    page.words = words.length;
    pages.push( page );
}

const n = rows.length;
const chars = rows.reduce( ( a, r ) => a + r.len, 0 );
const dist = rows.reduce( ( a, r ) => a + r.dist, 0 );
const count = ( list, verdict ) => list.filter( ( r ) => r.verdict === verdict ).length;
const pct = ( a, b ) => ( 100 * a / Math.max( 1, b ) ).toFixed( 1 ) + ' %';

let md = '# Reading against the text layer\n\n'
    + 'Generated by `tests/read.js` on ' + new Date().toISOString().slice( 0, 10 ) + '. ' + pages.length + ' pages, ' + n + ' read elements with reference text, ' + chars + ' reference characters. '
    + 'Compared in lower case with single spaces; near = Levenshtein distance at most ' + ( NEAR * 100 ) + ' % of the length.\n\n'
    + '| identical | near | different | empty | character errors |\n|---:|---:|---:|---:|---:|\n'
    + '| ' + count( rows, 'identical' ) + ' | ' + count( rows, 'near' ) + ' | ' + count( rows, 'different' ) + ' | ' + count( rows, 'empty' ) + ' | ' + pct( dist, chars ) + ' |\n\n'
    + '## By length of the reference\n\n| characters | elements | identical | near | different | empty | character errors |\n|---|---:|---:|---:|---:|---:|---:|\n';
for ( const [ lo, hi, label ] of LENGTHS ) {
    const part = rows.filter( ( r ) => r.len >= lo && r.len <= hi );
    if ( !part.length ) {
        continue;
    }
    md += '| ' + label + ' | ' + part.length + ' | ' + count( part, 'identical' ) + ' | ' + count( part, 'near' ) + ' | ' + count( part, 'different' ) + ' | ' + count( part, 'empty' )
        + ' | ' + pct( part.reduce( ( a, r ) => a + r.dist, 0 ), part.reduce( ( a, r ) => a + r.len, 0 ) ) + ' |\n';
}
md += '\n## The Fluffy flag against the verdict\n\nA flagged element (approve) is shown to a person. Right = identical; wrong = near, different or empty.\n\n| verdict | flagged | not flagged |\n|---|---:|---:|\n';
for ( const v of [ 'identical', 'near', 'different', 'empty' ] ) {
    md += '| ' + v + ' | ' + rows.filter( ( r ) => r.verdict === v && r.approve ).length + ' | ' + rows.filter( ( r ) => r.verdict === v && !r.approve ).length + ' |\n';
}
const wrong = rows.filter( ( r ) => r.verdict !== 'identical' );
const right = rows.filter( ( r ) => r.verdict === 'identical' );
md += '\nFlagged: ' + wrong.filter( ( r ) => r.approve ).length + ' of ' + wrong.length + ' wrong, ' + right.filter( ( r ) => r.approve ).length + ' of ' + right.length + ' right readings.\n';
md += '\nThe same from the measured deviation, for other thresholds (an empty reading counts as flagged):\n\n| threshold | wrong flagged | right flagged |\n|---:|---:|---:|\n';
for ( const t of THRESHOLDS ) {
    const flagged = ( r ) => r.verdict === 'empty' || ( r.deviation !== null && r.deviation > t );
    md += '| ' + t + ' | ' + wrong.filter( flagged ).length + ' of ' + wrong.length + ' | ' + right.filter( flagged ).length + ' of ' + right.length + ' |\n';
}
md += '\n## Per page\n\n| page | read elements | with reference | identical | near | different | empty | read, no reference text | reference words outside read elements |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n';
for ( const p of pages ) {
    md += '| ' + p.name + ' | ' + p.read + ' | ' + p.rows.length + ' | ' + count( p.rows, 'identical' ) + ' | ' + count( p.rows, 'near' ) + ' | ' + count( p.rows, 'different' ) + ' | ' + count( p.rows, 'empty' )
        + ' | ' + p.noReference + ' | ' + p.outside + ' of ' + p.words + ' |\n';
}
md += '\n## Different\n\n';
for ( const r of rows.filter( ( r ) => r.verdict === 'different' ) ) {
    md += '- ' + r.page + ' #' + r.i + ( r.approve ? ' (flagged)' : '' ) + ': reference “' + short( r.want ) + '” → read “' + short( r.have ) + '”\n';
}
md += '\n## Near\n\n';
for ( const r of rows.filter( ( r ) => r.verdict === 'near' ) ) {
    md += '- ' + r.page + ' #' + r.i + ( r.approve ? ' (flagged)' : '' ) + ': reference “' + short( r.want ) + '” → read “' + short( r.have ) + '”\n';
}

console.log( md.split( '\n## ' )[ 0 ] );
console.log( 'flagged: ' + wrong.filter( ( r ) => r.approve ).length + ' of ' + wrong.length + ' wrong, ' + right.filter( ( r ) => r.approve ).length + ' of ' + right.length + ' right' );
if ( outFile ) {
    await fs.mkdir( path.dirname( outFile ), { recursive: true } );
    await fs.writeFile( outFile, md );
    console.log( 'written ' + outFile );
}

// The words of the reference whose ink centre lies in the element, in reading order. The text layer carries
// boxes and circles as a single odd character ("ȅ Ja"); that is not text.
function referenceText( words, e ) {
    const inside = words.filter( ( w ) => {
        const cx = w.ink.x + Math.floor( w.ink.w / 2 );
        const cy = w.ink.y + Math.floor( w.ink.h / 2 );
        return cx >= e.x && cx <= e.x + e.width && cy >= e.y && cy <= e.y + e.height;
    } );
    inside.sort( ( a, b ) => a.line - b.line || a.x - b.x );
    return inside.map( ( w ) => w.t.replace( /[\x00-\x08\x0b-\x1f]/g, '' ) )
        .filter( ( t ) => t !== '' && !( [ ...t ].length === 1 && !/^[\x21-\x7eäöüÄÖÜéèàçâêîôûß§°–—«»]$/u.test( t ) ) )
        .join( ' ' );
}

function plain( t ) {
    return t.toLowerCase().replace( /[\s ]+/g, ' ' ).trim();
}

function short( t ) {
    return t.length > 70 ? t.slice( 0, 69 ) + '…' : t;
}
