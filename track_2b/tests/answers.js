import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../src/config.js';
import { createClient } from '../src/model/client.js';
import { createJob, saveJob } from '../src/job.js';
import { fillUnit, plain } from '../src/fields/filler.js';
import { parse } from '../src/dialogue/writer.js';
import { digits } from '../src/speech/numbers.js';
import { FORMS } from '../src/app/js/mock/forms.js';
import { DIALOGUES } from '../src/app/js/mock/dialogues.js';

// The dialogue end to end with a known truth: the walk-through's Betreibungsbegehren is asked question by
// question. A played respondent, the model itself, knows only the made-up dictation of the walk-through and
// answers every stored question; each answer goes into the fields of its unit; the made-up values are the
// reference. The same dictation and the same reference as tests/fill.js, where everything is said at once, so
// the two results stand side by side. Needs LLM_API_KEY; one call for the respondent and one per answer given.
//
//   node tests/answers.js [--out=<file.md>]

const outFile = ( process.argv.find( ( a ) => a.startsWith( '--out=' ) ) || '' ).slice( 6 );
if ( !config.apiKey ) {
    console.log( 'no LLM_API_KEY: nothing to measure' );
    process.exit( 1 );
}

const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
// the respondent's words for something the dictation does not hold
const UNKNOWN = /weiss ich nicht|weiß ich nicht/i;

const mock = FORMS.find( ( f ) => f.id === 'betreibungsbegehren' );
const job = createJob( { name: mock.name, issuer: mock.issuer, language: 'de', pages: 1, origin: 'original', file: 'forms/betreibungsbegehren/form.pdf' } );
job.pages = [ { n: 1, width: mock.page.w, height: mock.page.h, image: 'pages/1.png' } ];
job.fields = mock.sections.flatMap( ( s ) => s.fields ).map( ( f ) => ( { id: f.id, label: f.label, kind: f.kind, page: 1, x: f.x, y: f.y, width: f.w, height: f.h, ...( f.group ? { group: f.group, option: f.option } : {} ) } ) );
job.dialogue = { units: DIALOGUES[ mock.id ].map( ( u ) => ( { ...u, page: 1 } ) ) };
job.transcript = [];
await saveJob( job );

const client = createClient( config );
const log = path.join( config.storageDir, job.id, 'model' );
const started = Date.now();

// the respondent: every question at once, answered from the dictation alone
const story = mock.transcript.map( ( p ) => p.raw ).join( ' ' );
const lettered = job.dialogue.units.map( ( u, i ) => ( { letter: LETTERS[ i ], unit: u } ) );
const told = await client.ask( 'Du gibst jemandem im Gespräch Auskunft zu deinem Fall. Über den Fall weisst du nur, was du selbst so erzählt hast:\n\n' + story + '\n\n'
    + 'Dir werden diese Fragen gestellt:\n' + lettered.map( ( x ) => x.letter + ': ' + ( x.unit.question || x.unit.label ) ).join( '\n' ) + '\n\n'
    + 'Antworte auf jede Frage, wie man im Gespräch antwortet: kurz und nur mit dem, was du weisst. Weisst du etwas nicht, sag "Das weiss ich nicht.". '
    + 'Antworte nur als JSON, ohne weiteren Text: {"antworten": [{"frage": "A", "antwort": "..."}]}', { room: 60 * lettered.length + 400, log, tag: 'respondent' } );
const answers = new Map();
for ( const e of parse( told ? told.text : '', 'antworten', 'frage', 'antwort' ) ) {
    const x = lettered.find( ( l ) => l.letter === String( e.frage || '' ).trim().toUpperCase() );
    if ( x && !answers.has( x.unit.id ) ) {
        answers.set( x.unit.id, String( e.antwort || '' ).trim() );
    }
}

// each answer into the fields of its unit, as the transcriber would hand it on: number words already digits
let given = 0;
for ( const unit of job.dialogue.units ) {
    const raw = answers.get( unit.id ) || '';
    if ( !raw || UNKNOWN.test( raw ) ) {
        continue;
    }
    given++;
    const piece = { n: job.transcript.length + 1, start: 0, text: digits( raw ), raw, question: unit.id };
    job.transcript.push( piece );
    await fillUnit( job, unit, [ piece ], client );
}
const seconds = ( ( Date.now() - started ) / 1000 ).toFixed( 0 );

let md = '# Question by question: the walk-through\'s Betreibungsbegehren\n\nGenerated by `tests/answers.js` on ' + new Date().toISOString().slice( 0, 10 ) + ' with ' + config.model + '. '
    + job.dialogue.units.length + ' questions, ' + given + ' answered by the played respondent, ' + client.state.calls + ' calls, ' + seconds + ' s. '
    + 'The respondent knows only the made-up dictation; reference: the made-up values of the mock, as in `tests/fill.js` and `results/fill.md`, where the same dictation is said at once. '
    + 'same = letters and digits equal.\n\n'
    + '| field | question | answer | expected | state | got | how | approve | verdict |\n|---|---|---|---|---|---|---|---|---|\n';
const tally = { same: 0, different: 0, 'empty, expected empty': 0, 'empty, expected value': 0, 'value, expected empty': 0 };
let flagged = 0;
let off = 0;
for ( const unit of job.dialogue.units ) {
    for ( const id of unit.fields ) {
        const f = job.fields.find( ( x ) => x.id === id );
        const [ want, wantState ] = mock.values[ id ] || [ '', 'empty' ];
        const got = f.value || '';
        let verdict;
        if ( !got && !want ) {
            verdict = 'empty, expected empty';
        } else if ( !got ) {
            verdict = wantState === 'missing' ? 'empty, expected empty' : 'empty, expected value';
        } else if ( !want ) {
            verdict = 'value, expected empty';
        } else {
            verdict = plain( got ) === plain( want ) ? 'same' : 'different';
        }
        tally[ verdict ]++;
        if ( verdict === 'different' || verdict === 'value, expected empty' ) {
            off++;
            flagged += f.source && f.source.approve ? 1 : 0;
        }
        md += '| ' + id + ' | ' + ( unit.question || unit.label ).replace( /\|/g, '/' ) + ' | ' + ( answers.get( unit.id ) || '–' ).replace( /\|/g, '/' ) + ' | ' + ( want || '–' ) + ' | ' + wantState + ' | ' + ( got || '–' ) + ' | '
            + ( f.source ? f.source.how : '' ) + ' | ' + ( f.source && f.source.approve ? 'yes' : '' ) + ' | ' + verdict + ' |\n';
    }
}
md += '\n' + Object.entries( tally ).map( ( [ k, v ] ) => k + ': ' + v ).join( ' · ' ) + '\n'
    + '\nFlagged (approve) among the different and the values expected empty: ' + flagged + ' of ' + off + '.\n';
console.log( md );
if ( outFile ) {
    await fs.mkdir( path.dirname( outFile ), { recursive: true } );
    await fs.writeFile( outFile, md );
}
await fs.rm( path.join( config.storageDir, job.id ), { recursive: true, force: true } );
