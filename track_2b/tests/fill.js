import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from '../src/config.js';
import { createClient } from '../src/model/client.js';
import { createJob, saveJob } from '../src/job.js';
import { fillJob } from '../src/fields/filler.js';
import { FORMS } from '../src/app/js/mock/forms.js';
import { plain } from '../src/fields/filler.js';
import { digits } from '../src/speech/numbers.js';

// Dictation → fields with a known truth: the made-up dictation of the walk-through's Betreibungsbegehren goes in
// as the transcript, the made-up values are the reference. Needs LLM_API_KEY; three to four calls.
//
//   node tests/fill.js [--out=<file.md>]

const outFile = ( process.argv.find( ( a ) => a.startsWith( '--out=' ) ) || '' ).slice( 6 );
if ( !config.apiKey ) {
    console.log( 'no LLM_API_KEY: nothing to measure' );
    process.exit( 1 );
}
const mock = FORMS.find( ( f ) => f.id === 'betreibungsbegehren' );
const job = createJob( { name: mock.name, issuer: mock.issuer, language: 'de', pages: 1, origin: 'original', file: 'forms/betreibungsbegehren/form.pdf' } );
job.pages = [ { n: 1, width: mock.page.w, height: mock.page.h, image: 'pages/1.png' } ];
job.fields = mock.sections.flatMap( ( s ) => s.fields ).map( ( f ) => ( { id: f.id, label: f.label, kind: f.kind, page: 1, x: f.x, y: f.y, width: f.w, height: f.h, ...( f.group ? { group: f.group, option: f.option } : {} ) } ) );
// as the transcriber hands it on: number words already digits
job.transcript = mock.transcript.map( ( p, i ) => ( { n: i + 1, start: i * 30, text: digits( p.raw ), raw: p.raw, approve: false } ) );
await saveJob( job );

const client = createClient( config );
const started = Date.now();
await fillJob( job, client );
const seconds = ( ( Date.now() - started ) / 1000 ).toFixed( 0 );

let md = '# Dictation into fields: the walk-through\'s Betreibungsbegehren\n\nGenerated by `tests/fill.js` on ' + new Date().toISOString().slice( 0, 10 ) + '. '
    + job.transcript.length + ' transcript pieces, ' + job.fields.length + ' fields, ' + client.state.calls + ' calls, ' + seconds + ' s. '
    + 'Reference: the made-up values of the mock. same = letters and digits equal; the mock marks what it expects to be unclear or missing.\n\n'
    + '| field | expected | state | got | how | approve | verdict |\n|---|---|---|---|---|---|---|\n';
const tally = { same: 0, different: 0, 'empty, expected empty': 0, 'empty, expected value': 0, 'value, expected empty': 0 };
for ( const f of job.fields ) {
    const [ want, wantState ] = mock.values[ f.id ] || [ '', 'empty' ];
    const got = f.value || '';
    let verdict;
    if ( !got && !want ) {
        verdict = 'empty, expected empty';
    } else if ( !got ) {
        verdict = wantState === 'missing' ? 'empty, expected empty' : 'empty, expected value';
    } else if ( !want ) {
        verdict = 'value, expected empty';
    } else {
        verdict = plain( got ) === plain( want ) ? 'same' : 'different';
    }
    tally[ verdict ]++;
    md += '| ' + f.id + ' | ' + ( want || '–' ) + ' | ' + wantState + ' | ' + ( got || '–' ) + ' | ' + ( f.source ? f.source.how : '' ) + ' | ' + ( f.source && f.source.approve ? 'yes' : '' ) + ' | ' + verdict + ' |\n';
}
md += '\n' + Object.entries( tally ).map( ( [ k, v ] ) => k + ': ' + v ).join( ' · ' ) + '\n';
const hinted = job.fields.filter( ( f ) => f.hints && f.hints.length );
if ( hinted.length ) {
    md += '\n## Hints\n\n| field | kind | text | article |\n|---|---|---|---|\n';
    for ( const f of hinted ) {
        for ( const h of f.hints ) {
            md += '| ' + f.id + ' | ' + h.kind + ' | ' + ( h.text || '' ).replace( /\|/g, '/' ).slice( 0, 160 ) + ' | ' + ( h.article || '' ) + ' |\n';
        }
    }
}
md += '\nFlagged (approve) among the different and the values expected empty: ' + job.fields.filter( ( f ) => f.source && f.source.approve && ( !mock.values[ f.id ] || plain( f.value ) !== plain( mock.values[ f.id ][ 0 ] ) ) ).length + '\n';
console.log( md );
if ( outFile ) {
    await fs.mkdir( path.dirname( outFile ), { recursive: true } );
    await fs.writeFile( outFile, md );
}
await fs.rm( path.join( config.storageDir, job.id ), { recursive: true, force: true } );
