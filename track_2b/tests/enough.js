import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../src/config.js';
import { createClient } from '../src/model/client.js';
import { judgeEnough } from '../src/review/hints.js';
import { FORMS } from '../src/app/js/mock/forms.js';
import { DIALOGUES } from '../src/app/js/mock/dialogues.js';

// Is an answer enough for its place? The judgement the app makes after every answer to a single field, measured
// on cases built from the two walk-through forms and their made-up values, without a hand label. Per unit that
// carries a value: the value itself as the answer (expected: enough), "I don't know" (not enough), the value of
// the next unit (not enough; it may still fit the place by its kind), and, where the label asks for several
// things, only the first part of the value (not enough; an assumption, not a truth). The full answers are judged
// a second time for stability. Needs API_KEY; one call per case, 129 calls.
//
//   node tests/enough.js [--out=<file.md>]

const outFile = ( process.argv.find( ( a ) => a.startsWith( '--out=' ) ) || '' ).slice( 6 );
if ( !config.apiKey ) {
    console.log( 'no API_KEY: nothing to measure' );
    process.exit( 1 );
}

// a label that asks for several things
const SEVERAL = /;| und | mit /;

const cases = [];
for ( const mock of FORMS ) {
    const fields = mock.sections.flatMap( ( s ) => s.fields );
    const units = DIALOGUES[ mock.id ].map( ( u ) => {
        const own = u.fields.map( ( id ) => fields.find( ( f ) => f.id === id ) );
        const said = own.filter( ( f ) => ( mock.values[ f.id ] || [ '' ] )[ 0 ] );
        // the unit's value as a spoken answer: the value, or for a choice the name of the option
        const value = said.map( ( f ) => ( f.kind === 'checkbox' || f.kind === 'radio' ? f.option || f.label : mock.values[ f.id ][ 0 ] ) ).join( ', ' );
        return { unit: u, field: own[ 0 ], value };
    } ).filter( ( x ) => x.value );
    units.forEach( ( x, i ) => {
        const base = { form: mock.id, unit: x.unit, field: x.field };
        cases.push( { ...base, type: 'the value itself', answer: x.value, enough: true } );
        cases.push( { ...base, type: '"Das weiss ich nicht."', answer: 'Das weiss ich nicht.', enough: false } );
        cases.push( { ...base, type: 'the value of the next unit', answer: units[ ( i + 1 ) % units.length ].value, enough: false } );
        const parts = x.value.split( /,\s*/ );
        if ( x.unit.kind === 'single' && SEVERAL.test( x.unit.label ) && parts.length >= 2 ) {
            cases.push( { ...base, type: 'only the first part of the value', answer: parts[ 0 ], enough: false } );
        }
    } );
}

const client = createClient( config );
const job = { id: path.join( 'bench', 'enough' ) };
const started = Date.now();
const judge = async ( c ) => {
    const hint = await judgeEnough( job, c.unit, c.field, c.answer, client );
    return hint ? hint.text : null;
};
for ( const c of cases ) {
    c.missing = await judge( c );
    if ( client.state.halted ) {
        console.log( 'halted by HTTP ' + client.state.halted );
        process.exit( 1 );
    }
}
const full = cases.filter( ( c ) => c.enough );
for ( const c of full ) {
    c.again = await judge( c );
}

const types = [ ...new Set( cases.map( ( c ) => c.type ) ) ];
let md = '# Is an answer enough for its place?\n\nGenerated by `tests/enough.js` on ' + new Date().toISOString().slice( 0, 10 ) + ' with ' + config.model + ' at temperature 0, one judgement per call, ' + client.state.calls + ' calls, '
    + Math.round( ( Date.now() - started ) / 1000 ) + ' s with the pauses. Cases from the two walk-through forms and their made-up values, ' + full.length + ' units with a value. '
    + 'Taken as enough = the judgement leaves no hint; held back = it leaves an `incomplete` hint that says what is missing.\n\n'
    + '| answer | expected | cases | taken as enough | held back |\n|---|---|---:|---:|---:|\n';
for ( const type of types ) {
    const all = cases.filter( ( c ) => c.type === type );
    md += '| ' + type + ' | ' + ( all[ 0 ].enough ? 'enough' : 'not enough' ) + ' | ' + all.length + ' | ' + all.filter( ( c ) => c.missing === null ).length + ' | ' + all.filter( ( c ) => c.missing !== null ).length + ' |\n';
}
md += '\nThe full answers judged a second time: the same verdict in ' + full.filter( ( c ) => ( c.again === null ) === ( c.missing === null ) ).length + ' of ' + full.length + '.\n\n'
    + 'Without the model, "not empty and not \'I don\'t know\'" takes every case but the second row as enough.\n\n'
    + '## Where the judgement and the expectation part\n\n| form | question | printed label | answer | judged | missing |\n|---|---|---|---|---|---|\n'
    + cases.filter( ( c ) => c.enough !== ( c.missing === null ) ).map( ( c ) => '| ' + c.form + ' | ' + ( c.unit.question || c.unit.label ) + ' | ' + c.unit.label.slice( 0, 60 ) + ' | ' + c.answer.slice( 0, 70 ) + ' | '
        + ( c.missing === null ? 'enough' : 'not enough' ) + ' | ' + ( c.missing || '' ).slice( 0, 80 ) + ' |' ).join( '\n' ) + '\n';
console.log( md );
if ( outFile ) {
    await fs.mkdir( path.dirname( outFile ), { recursive: true } );
    await fs.writeFile( outFile, md );
}
