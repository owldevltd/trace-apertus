import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../src/config.js';
import { createClient } from '../src/model/client.js';
import { LARGE } from '../src/review/catalogue.js';
import { loadCatalogue } from '../src/review/hints.js';
import { bindRequired } from '../src/dialogue/required.js';
import { close } from '../src/workers.js';
import { jobDir, loadRun } from '../src/job.js';
import { runPipeline } from '../src/pipeline.js';
import { listShipped, startShipped, keepCaptured } from '../src/shipped.js';

// Captures the shipped forms: runs the pipeline over each one once, as the app does for a photographed form, and
// keeps what it found beside the form as data/forms/<form>/captured.json (pages, blocks, fields, dialogue). The
// app then opens a shipped form without recognizing anything. The text comes from the text layer of the PDF; the
// questions of the dialogue are written and checked by the model, 47 calls for the four forms, and the questions
// at which a form requires an entry are marked from its catalogue, 29 calls. A preparation
// step, its result is committed; a form's questions are written once and kept, not anew for every job.
// Needs API_KEY.
//
// With --required only the last part is done anew on what is kept: the required entries of the form's catalogue
// are bound to the questions (29 calls for the four forms), the questions themselves stay as they are, and
// --out=<file.md> gets the report of that binding.
//
//   node --env-file=.env tools/capture.js [--required [--out=<file.md>]] [<form> …]

if ( !config.apiKey ) {
    console.log( 'no API_KEY: the forms would be captured without questions' );
    process.exit( 1 );
}

const only = process.argv.slice( 2 ).filter( ( a ) => !a.startsWith( '--' ) );
const outFile = ( process.argv.find( ( a ) => a.startsWith( '--out=' ) ) || '' ).slice( 6 );
const client = createClient( config );
const forms = ( await listShipped() ).filter( ( f ) => !only.length || only.includes( f.id ) );

if ( process.argv.includes( '--required' ) ) {
    const log = outFile ? path.join( path.dirname( outFile ), 'required-model' ) : null;
    const cut = ( t ) => ( t || '–' ).replace( /\|/g, '/' ).slice( 0, 70 );
    let rows = '';
    let read = '';
    for ( const form of forms ) {
        const file = path.join( config.dataDir, 'forms', form.id, 'captured.json' );
        const captured = JSON.parse( await fs.readFile( file, 'utf8' ) );
        const catalogue = await loadCatalogue( captured );
        const before = client.state.calls;
        const bound = catalogue ? await bindRequired( captured, catalogue, client, log ) : [];
        if ( client.state.halted ) {
            console.log( form.id + ': halted by HTTP ' + client.state.halted + ', nothing kept' );
            process.exit( 1 );
        }
        await fs.writeFile( file, JSON.stringify( captured ) + '\n' );
        const units = captured.dialogue.units;
        const count = ( how ) => bound.filter( ( b ) => b.how === how ).length;
        rows += '| ' + form.id + ' | ' + bound.length + ' | ' + count( 'label' ) + ' | ' + count( 'models' ) + ' | ' + bound.filter( ( b ) => b.dropped.length ).length + ' | ' + count( null ) + ' | '
            + units.filter( ( u ) => u.required ).length + ' of ' + units.filter( ( u ) => !u.skip ).length + ' | ' + ( client.state.calls - before ) + ' |\n';
        for ( const b of bound ) {
            const named = ( list ) => list.map( ( q ) => q + ' ' + cut( units.find( ( u ) => u.id === q ).label ) ).join( '; ' ) || '–';
            read += '| ' + form.id + ' | ' + cut( b.field ) + ' | ' + ( b.how || 'not bound' ) + ' | ' + named( b.units ) + ' | ' + named( b.dropped ) + ' |\n';
        }
        console.log( form.id.padEnd( 28 ) + ' ' + bound.length + ' required entries, ' + units.filter( ( u ) => u.required ).length + ' questions marked, ' + ( client.state.calls - before ) + ' calls  → ' + file );
    }
    if ( outFile ) {
        await fs.mkdir( path.dirname( outFile ), { recursive: true } );
        await fs.writeFile( outFile, '# Required: the questions at which a form requires an entry\n\n'
            + 'Generated by `tools/capture.js --required` on ' + new Date().toISOString().slice( 0, 10 ) + ' with ' + config.model + ' and ' + LARGE + ', ' + client.state.calls + ' calls. '
            + 'What is required stands in the catalogue of a form, checked by a person. An entry is bound to a question by the label of a field; where no label says so, by the unit both models name, '
            + 'when the check back names the same entry for it. The marks are kept in `data/forms/<form>/captured.json`.\n\n'
            + '| form | required entries in the catalogue | bound by the label | bound by both models and the check back | with a unit the check back dropped | not bound | questions marked required | calls |\n'
            + '|---|---:|---:|---:|---:|---:|---|---:|\n' + rows
            + '\n## Every required entry, to read\n\n| form | required entry | bound by | questions | named by both models, dropped by the check back |\n|---|---|---|---|---|\n' + read );
        console.log( 'written ' + outFile );
    }
    process.exit( 0 );
}

for ( const form of forms ) {
    const before = client.state.calls;
    const { job } = await startShipped( form.id, true );
    await runPipeline( job, client );
    const run = await loadRun( job.id );
    if ( run.step !== 'done' || client.state.halted ) {
        console.log( form.id + ': ' + ( client.state.halted ? 'halted by HTTP ' + client.state.halted : run.error ) + ', nothing kept' );
        close();
        process.exit( 1 );
    }
    const file = await keepCaptured( form.id, job );
    const units = job.dialogue.units;
    console.log( form.id.padEnd( 28 ) + ' ' + job.pages.length + ' pages, ' + job.fields.length + ' fields, ' + units.length + ' units, ' + units.filter( ( u ) => u.skip ).length + ' not asked, '
        + units.filter( ( u ) => u.question ).length + ' with a question, ' + units.filter( ( u ) => u.required ).length + ' required, ' + ( client.state.calls - before ) + ' calls  → ' + file );
    await fs.rm( jobDir( job.id ), { recursive: true, force: true } );
}
close();
